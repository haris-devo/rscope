import type { RouteResult, Violation } from "./budget.js";
import { METRICS } from "./budget.js";
import { propTree } from "./props.js";
import { formatBytes, formatPercent } from "./units.js";

const BUCKET_LABELS = {
  clientProps: "Client component props",
  serverTree: "Server-rendered tree",
  frameworkProps: "Next.js internals",
  modules: "Module references",
  hints: "Preload hints",
  other: "Other",
} as const;

export { BUCKET_LABELS };

function escape(text: string): string {
  return text.replace(/[|`*_<>[\]\\]/g, (c) => `\\${c}`);
}

function largest(result: RouteResult): string {
  const top = result.report.components.find((c) => !c.framework && c.propsBytes > 0);
  if (!top) return "–";
  const instances = top.instances > 1 ? ` ×${top.instances}` : "";
  return `\`${top.name}\`${instances} · ${formatBytes(top.propsBytes)}`;
}

/** A Markdown report for a PR comment or a GitHub Actions job summary. */
export function toMarkdown(results: RouteResult[], violations: Violation[], options: { top?: number } = {}): string {
  const top = options.top ?? 5;
  const over = new Set(violations.map((v) => v.route));
  const lines: string[] = [];

  lines.push("## rscope: RSC payload report", "");
  lines.push(
    violations.length === 0
      ? `✅ ${results.length} route${results.length === 1 ? "" : "s"} within budget.`
      : `❌ ${over.size} of ${results.length} routes over budget.`,
    "",
  );

  lines.push("| | Route | Payload | gzip | Document | Client props | Largest client component |");
  lines.push("|---|---|---:|---:|---:|---:|---|");
  for (const result of results) {
    const { report } = result;
    lines.push(
      [
        "",
        over.has(result.route) ? "❌" : "✅",
        `\`${escape(result.route)}\``,
        formatBytes(report.payloadBytes),
        result.gzip ? formatBytes(result.gzip.payload) : "–",
        report.documentBytes ? formatBytes(report.documentBytes) : "–",
        `${formatBytes(report.breakdown.clientProps)} (${formatPercent(report.breakdown.clientProps, report.payloadBytes)})`,
        largest(result),
        "",
      ].join(" | ").trim(),
    );
  }
  lines.push("");

  if (violations.length > 0) {
    lines.push("### Over budget", "");
    for (const v of violations) {
      lines.push(`- \`${escape(v.route)}\`: ${METRICS[v.metric]} is **${formatBytes(v.actual)}**, budget ${formatBytes(v.limit)}`);
    }
    lines.push("");
  }

  const withFindings = results.filter((r) => r.report.findings.some((f) => f.severity === "warning"));
  if (withFindings.length > 0) {
    lines.push("### Findings", "");
    for (const result of withFindings) {
      lines.push(`<details><summary><code>${escape(result.route)}</code></summary>`, "");
      for (const finding of result.report.findings) {
        lines.push(`- **${escape(finding.title)}**  `, `  ${escape(finding.detail)}`);
      }
      const heavy = result.report.components.filter((c) => !c.framework && c.propsBytes > 0).slice(0, top);
      if (heavy.length > 0) {
        lines.push("", "| Component | Instances | Props | Biggest fields |", "|---|---:|---:|---|");
        for (const c of heavy) {
          const fields = propTree(c, 3, 2)
            .flatMap((node) => (node.children.length > 0 && node.bytes > c.propsBytes / 2 ? node.children : [node]))
            .slice(0, 3)
            .map((node) => `\`${escape(node.path)}\` ${formatBytes(node.bytes)}`)
            .join(", ");
          lines.push(`| \`${escape(c.name)}\` | ${c.instances} | ${formatBytes(c.propsBytes)} | ${fields} |`);
        }
      }
      lines.push("", "</details>", "");
    }
  }

  lines.push("<sub>Generated by [rscope](https://github.com/haris-devo/rscope). 1 kB = 1000 bytes.</sub>", "");
  return lines.join("\n");
}
